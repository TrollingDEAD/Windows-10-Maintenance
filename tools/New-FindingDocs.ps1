#requires -version 5.1
<#
.SYNOPSIS
    Generates docs/FINDINGS.md from the Add-Finding calls in Windows10_SystemMaintenance.ps1.

.DESCRIPTION
    Parses the script with the PowerShell AST (nothing is executed), collects every Add-Finding call and writes one
    section per finding ID: severity, category, what it means and what to do. Findings whose ID is built at run time
    (for example "disk-health-<DeviceId>") are listed under their static prefix.
    Run it after adding or changing findings; CI fails when docs/FINDINGS.md is out of date.

.PARAMETER Check
    Do not write; exit with code 1 if docs/FINDINGS.md differs from what would be generated.
#>
[CmdletBinding()]
param([switch]$Check)

$root = Split-Path $PSScriptRoot -Parent
$scriptPath = Join-Path $root 'Windows10_SystemMaintenance.ps1'
$outPath = Join-Path $root 'docs\FINDINGS.md'

$ast = [System.Management.Automation.Language.Parser]::ParseFile($scriptPath, [ref]$null, [ref]$null)
$calls = $ast.FindAll({ param($n) $n -is [System.Management.Automation.Language.CommandAst] -and $n.GetCommandName() -eq 'Add-Finding' }, $true)

function Get-Text($node) {
    if ($null -eq $node) { return '' }
    if ($node -is [System.Management.Automation.Language.StringConstantExpressionAst]) { return $node.Value }
    if ($node -is [System.Management.Automation.Language.ExpandableStringExpressionAst]) { return $node.Value }
    return $node.Extent.Text
}
function Get-Anchor([string]$id) { return (($id.ToLower() -replace '[^a-z0-9]+', '-').Trim('-')) }

$items = @{}
foreach ($c in $calls) {
    $p = @{}
    $els = @($c.CommandElements)
    for ($i = 1; $i -lt $els.Count; $i++) {
        if ($els[$i] -is [System.Management.Automation.Language.CommandParameterAst]) {
            $name = $els[$i].ParameterName
            $val = if ($els[$i].Argument) { $els[$i].Argument } elseif ($i + 1 -lt $els.Count) { $els[$i + 1] } else { $null }
            $p[$name] = Get-Text $val
        }
    }
    if (-not $p.ContainsKey('Id')) { continue }
    $id = $p['Id']
    $dynamic = $id -match '\$'
    $static = if ($dynamic) { ($id -replace '\$.*$', '').TrimEnd('-') } else { $id }
    if (-not $static) { continue }
    $key = $static
    if (-not $items.ContainsKey($key)) {
        $items[$key] = [pscustomobject]@{
            Id = $static; Dynamic = $dynamic; Severity = $p['Severity']; Category = $p['Category']
            Title = $p['Title']; Meaning = $p['Meaning']; Recommendation = $p['Recommendation']
        }
    }
}

# Strip run-time expressions from texts so the page reads cleanly
function Clear-Expr([string]$s) {
    if (-not $s) { return '' }
    $s = $s -replace '\$\([^)]*\)', '…' -replace '\$\w+(\.\w+)*', '…' -replace '`', ''
    return $s.Trim()
}

$sevOrder = @{ 'Critical' = 0; 'High' = 1; 'Medium' = 2; 'Low' = 3; 'Info' = 4 }
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('# Findings reference')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('<!-- Generated by tools/New-FindingDocs.ps1 - do not edit by hand. -->')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('Every problem the script reports has a stable **finding ID**. This page explains what each one means and what to do about it. The severity shown is the default; some findings change their severity depending on the evidence.')
[void]$sb.AppendLine('')
[void]$sb.AppendLine("Total: **$($items.Count)** findings. IDs ending in a dash-placeholder (for example ``disk-health-<id>``) exist once per drive, adapter or event source.")
[void]$sb.AppendLine('')
foreach ($cat in ($items.Values | Group-Object Category | Sort-Object Name)) {
    [void]$sb.AppendLine("## $($cat.Name)")
    [void]$sb.AppendLine('')
    foreach ($f in ($cat.Group | Sort-Object { $sevOrder[$_.Severity] }, Id)) {
        $shown = if ($f.Dynamic) { "$($f.Id)-<…>" } else { $f.Id }
        [void]$sb.AppendLine("<a id=""$(Get-Anchor $f.Id)""></a>")
        [void]$sb.AppendLine("### ``$shown``")
        [void]$sb.AppendLine('')
        [void]$sb.AppendLine("**Severity:** $($f.Severity) · **Title:** $(Clear-Expr $f.Title)")
        [void]$sb.AppendLine('')
        [void]$sb.AppendLine("**What it means.** $(Clear-Expr $f.Meaning)")
        [void]$sb.AppendLine('')
        if ($f.Recommendation) { [void]$sb.AppendLine("**What to do.** $(Clear-Expr $f.Recommendation)"); [void]$sb.AppendLine('') }
        [void]$sb.AppendLine("Suppress it (if you accept the risk): add ``""$($f.Id)$(if ($f.Dynamic) { '*' })""`` to ``SuppressFindings`` in the config file.")
        [void]$sb.AppendLine('')
    }
}
$new = $sb.ToString() -replace "`r`n", "`n"

if ($Check) {
    $old = if (Test-Path -LiteralPath $outPath) { (Get-Content -LiteralPath $outPath -Raw -Encoding UTF8) -replace "`r`n", "`n" } else { '' }
    if ($old.TrimEnd() -ne $new.TrimEnd()) { Write-Host 'docs/FINDINGS.md is out of date. Run tools/New-FindingDocs.ps1.' -ForegroundColor Red; exit 1 }
    Write-Host 'docs/FINDINGS.md is up to date.' -ForegroundColor Green
    exit 0
}
New-Item -ItemType Directory -Path (Split-Path $outPath -Parent) -Force | Out-Null
[IO.File]::WriteAllText($outPath, $new, (New-Object System.Text.UTF8Encoding($false)))
Write-Host "Wrote $outPath ($($items.Count) findings)." -ForegroundColor Green
